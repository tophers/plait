var updateFixtures = flag.Bool("update-fixtures", false, "rewrite web/test/fixtures.json")

const fixturePath = "../../web/test/fixtures.json"

type keyFixture struct {
	Private string `json:"private"`
	Public  string `json:"public"`
}

type profileFixture struct {
	Name     string                    `json:"name"`
	Material *protocol.ProfileMaterial `json:"material"`
	Private  string                    `json:"private"`
	Full     string                    `json:"full"`
	Minified string                    `json:"minified"`
}

type fixtures struct {
	Comment  string           `json:"_comment"`
	Keys     []keyFixture     `json:"keys"`
	Profiles []profileFixture `json:"profiles"`
}

// detKey derives a deterministic clamped private key so fixtures are stable.
func detKey(seed string) wg.Key {
	k := wg.Key(sha256.Sum256([]byte(seed)))
	k[0] &= 248
	k[31] = (k[31] & 127) | 64
	return k
}

func pubOf(k wg.Key) wg.Key {
	p, _ := k.PublicKey()
	return p
}

// material builds profile material with n site peers, each with two prefixes.
func material(n int, dev wg.Key, extras bool) *protocol.ProfileMaterial {
	m := &protocol.ProfileMaterial{
		SchemaVersion: protocol.ProfileSchemaVersion, DeviceID: fmt.Sprintf("dev-%d", n), DeviceName: "phone",
		Revision: int64(3 + n), PublicKey: pubOf(dev), Address: netip.MustParsePrefix("10.0.0.4/32"),
		Peers: []protocol.ProfilePeer{},
	}
	if extras {
		m.MTU = 1380
		m.DNSServers = []netip.Addr{netip.MustParseAddr("10.13.37.37"), netip.MustParseAddr("10.15.0.53")}
		m.SearchDomains = []string{"home.lan", "cabin.lan"}
	}
	for i := 0; i < n; i++ {
		keepalive := 25
		if i%3 == 2 {
			keepalive = 0
		}
		m.Peers = append(m.Peers, protocol.ProfilePeer{
			SiteID: fmt.Sprintf("site-%02d", i), SiteName: fmt.Sprintf("Site %d", i),
			PublicKey:           pubOf(detKey(fmt.Sprintf("site-%d", i))),
			Endpoint:            fmt.Sprintf("site%d.gateway.example.net:51111", i),
			AllowedIPs:          []netip.Prefix{netip.PrefixFrom(netip.AddrFrom4([4]byte{10, byte(16 + i), 0, 0}), 24), netip.PrefixFrom(netip.AddrFrom4([4]byte{172, byte(16 + i), 1, 0}), 24)},
			PresharedKey:        detKey(fmt.Sprintf("psk-%d", i)),
			PersistentKeepalive: keepalive,
		})
	}
	if n == 1 && !extras {
		m.Peers[0].Endpoint = "[2001:db8::1]:51111"
	}
	return m
}

func buildFixtures(t *testing.T) []byte {
	f := fixtures{Comment: "Generated by `go test ./internal/ui -run TestFixtures -update-fixtures`. JS must match these Go results exactly."}
	// RFC 7748 6.1 vector, then deterministic keys.
	rfcPriv := wg.Key{0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d, 0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45,
		0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a, 0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a}
	f.Keys = append(f.Keys, keyFixture{rfcPriv.String(), pubOf(rfcPriv).String()})
	for i := 0; i < 16; i++ {
		k := detKey(fmt.Sprintf("key-%d", i))
		f.Keys = append(f.Keys, keyFixture{k.String(), pubOf(k).String()})
	}
	for _, c := range []struct {
		n      int
		extras bool
	}{{0, false}, {1, false}, {2, true}, {4, true}, {8, true}, {16, true}, {24, true}} {
		dev := detKey(fmt.Sprintf("device-%d", c.n))
		m := material(c.n, dev, c.extras)
		full, err := profile.Render(m, dev, profile.Options{})
		if err != nil {
			t.Fatal(err)
		}
		min, err := profile.Render(m, dev, profile.Options{Minify: true})
		if err != nil {
			t.Fatal(err)
		}
		f.Profiles = append(f.Profiles, profileFixture{Name: fmt.Sprintf("%d peers", c.n), Material: m, Private: dev.String(), Full: full, Minified: min})
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return append(out, '\n')
}

// TestFixtures keeps the committed JS fixtures in sync with the Go renderer.
func TestFixtures(t *testing.T) {
	want := buildFixtures(t)
	if *updateFixtures {
		if err := os.WriteFile(fixturePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatalf("%v (run with -update-fixtures)", err)
	}
	if string(got) != string(want) {
		t.Fatal("web/test/fixtures.json is stale; run: go test ./internal/ui -run TestFixtures -update-fixtures")
	}
}
