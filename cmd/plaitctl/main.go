// Command plaitctl is Plait's local administration and enrollment helper.
// Private keys are generated and used only locally; the controller never
// receives them.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"strings"

	"plait/internal/model"
)

const usage = `usage: plaitctl <command> [flags]

Keys (local only):
  genkey                      print a new private key
  pubkey                      read a private key on stdin, print its public key
  init-key <path>             create a new encryption key file for PSKs and TOTP secrets (mode 0600)

Local administration (reads $PLAIT_CONFIG, default /etc/plait/plaitd.json):
  admin create|password|totp-reset <username> | admin count
  site add|update|list|enable|disable|snapshot|enroll-token|revoke-credentials|status
  device enroll|list|enable|disable|retire|delete|rename|replace-key|settings
  link add|enable|disable|keepalive|rotate-psk
  profile <device> -private-key-file <path> [-minify] [-o file]
  audit [-n 50]
  tls status                  how plaitd serves TLS; the CA fingerprint gateways pin
  tls auto [-name N]...       use a certificate generated by plaitd (the default)
  tls files -cert F -key K    use certificate files (reloaded when they change)

Backup and recovery:
  backup <dest.db>            consistent copy (the encryption key file is separate)
  restore <backup.db>         stop plaitd first; enters recovery
  recover status|complete
`

func main() {
	if len(os.Args) < 2 {
		fmt.Fprint(os.Stderr, usage)
		os.Exit(2)
	}
	err := run(os.Args[1], os.Args[2:], os.Stdin, os.Stdout)
	if errors.Is(err, flag.ErrHelp) {
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "plaitctl:", err)
		if model.IsValidation(err) {
			os.Exit(3)
		}
		os.Exit(1)
	}
}

func run(cmd string, args []string, stdin io.Reader, stdout io.Writer) error {
	switch cmd {
	case "genkey":
		return cmdGenkey(stdout)
	case "pubkey":
		return cmdPubkey(stdin, stdout)
	case "init-key":
		return cmdInitKey(args)
	case "site":
		return withAdmin(args, cmdSite)
	case "device":
		return withAdmin(args, cmdDevice)
	case "link":
		return withAdmin(args, cmdLink)
	case "profile":
		return withAdmin(append([]string{"profile"}, args...), cmdProfile)
	case "admin":
		return withAdmin(args, cmdAdmin)
	case "audit":
		return withAdmin(args, cmdAudit)
	case "backup":
		return withAdmin(args, cmdBackup)
	case "restore":
		return cmdRestore(args)
	case "tls":
		return cmdTLS(args, stdout)
	case "recover":
		return withAdmin(args, cmdRecover)
	case "help", "-h", "--help":
		fmt.Fprint(stdout, usage)
		return nil
	}
	return fmt.Errorf("unknown command %q\n%s", cmd, usage)
}

// stringList is a repeatable flag.
type stringList []string

func (s *stringList) String() string { return strings.Join(*s, ",") }
func (s *stringList) Set(v string) error {
	for _, part := range strings.Split(v, ",") {
		if part = strings.TrimSpace(part); part != "" {
			*s = append(*s, part)
		}
	}
	return nil
}
